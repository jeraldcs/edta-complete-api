"""Run all trained travel scenarios and collect scoring metrics."""

from __future__ import annotations

from typing import Any

from app.empathy.trained_scenarios import TRAINED_SCENARIOS


def extract_scenario_scores(response_body: dict[str, Any], scenario_key: str, scenario_meta: dict[str, Any]) -> dict[str, Any]:
    summary = response_body.get("request_summary") or {}
    recommendations = response_body.get("recommendations") or []
    top = recommendations[0] if recommendations else {}
    candidate = top.get("candidate") or {}
    ai = top.get("ai_score") or {}
    eds = top.get("eds_score") or {}
    tapl = ai.get("tapl") or {}
    outcome = ai.get("outcome_simulation") or {}
    empathy = summary.get("empathy") or {}
    empathy_vehicle = empathy.get("vehicle_recommendation") or {}
    profile = summary.get("scenario_profile") or {}
    expected = scenario_meta.get("expected_vehicle")

    top_id = candidate.get("id")
    empathy_id = empathy_vehicle.get("candidate_id")
    top_rank_match = top_id == expected
    empathy_match = empathy_id == expected
    vehicle_match = top_rank_match or empathy_match

    return {
        "scenario_key": scenario_key,
        "title": scenario_meta.get("title") or scenario_key,
        "objective": scenario_meta.get("objective") or profile.get("objective"),
        "profile_id": profile.get("profile_id"),
        "expected_vehicle": expected,
        "top_vehicle": top_id,
        "empathy_vehicle": empathy_id,
        "top_rank_match": top_rank_match,
        "empathy_match": empathy_match,
        "vehicle_match": vehicle_match,
        "eds_score": eds.get("final_eds_score"),
        "semantic_score": ai.get("semantic_similarity_score"),
        "channel_fit": ai.get("channel_fit_score"),
        "conversion_probability": outcome.get("conversion_probability"),
        "expected_outcome": outcome.get("expected_outcome_score"),
        "revenue_impact": outcome.get("revenue_impact"),
        "trust_impact": outcome.get("trust_impact"),
        "journey_impact": outcome.get("journey_impact"),
        "tapl_action": tapl.get("action"),
        "trust_score": tapl.get("trust_score"),
        "fatigue_score": tapl.get("fatigue_score"),
        "compliance_score": tapl.get("compliance_score"),
        "ai_rank_score": ai.get("ai_rank_score"),
        "final_hybrid_score": ai.get("final_hybrid_score"),
        "trip_miles": (empathy.get("trip") or {}).get("distance_miles"),
        "persona": profile.get("persona"),
        "scenario_text": scenario_meta.get("text"),
    }


def run_travel_benchmark(recommend_fn) -> dict[str, Any]:
    """recommend_fn(scenario_text) -> response dict"""
    rows: list[dict[str, Any]] = []
    for key, meta in TRAINED_SCENARIOS.items():
        body = recommend_fn(meta["text"])
        rows.append(extract_scenario_scores(body, key, meta))

    matched = sum(1 for row in rows if row.get("vehicle_match"))
    top_matched = sum(1 for row in rows if row.get("top_rank_match"))
    return {
        "scenario_count": len(rows),
        "vehicle_match_count": matched,
        "vehicle_match_rate": round(matched / len(rows), 4) if rows else 0.0,
        "top_rank_match_count": top_matched,
        "top_rank_match_rate": round(top_matched / len(rows), 4) if rows else 0.0,
        "scenarios": rows,
    }


def benchmark_to_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# Travel Scenario Score Matrix",
        "",
        f"**Scenarios:** {payload.get('scenario_count', 0)} | "
        f"**Vehicle match rate:** {payload.get('vehicle_match_rate', 0):.0%}",
        "",
        "| # | Scenario | Profile | Top vehicle | Empathy vehicle | EDS | Semantic | Outcome | Conv. | TAPL | Trust | Fatigue | Base rank | Final | Match |",
        "|---:|---|---|---|---|---:|---:|---:|---:|---|---:|---:|---:|---:|:---:|",
    ]
    for index, row in enumerate(payload.get("scenarios") or [], start=1):
        match = "yes" if row.get("vehicle_match") else "no"
        lines.append(
            f"| {index} "
            f"| {row.get('title', '')} "
            f"| {row.get('profile_id') or '—'} "
            f"| {row.get('top_vehicle') or '—'} "
            f"| {row.get('empathy_vehicle') or '—'} "
            f"| {_fmt(row.get('eds_score'))} "
            f"| {_fmt(row.get('semantic_score'))} "
            f"| {_fmt(row.get('expected_outcome'))} "
            f"| {_fmt(row.get('conversion_probability'))} "
            f"| {row.get('tapl_action') or '—'} "
            f"| {_fmt(row.get('trust_score'))} "
            f"| {_fmt(row.get('fatigue_score'))} "
            f"| {_fmt(row.get('ai_rank_score'))} "
            f"| {_fmt(row.get('final_hybrid_score'))} "
            f"| {match} |"
        )
    lines.extend(["", "_Generated by `scripts/benchmark_travel_scenarios.py`_", ""])
    return "\n".join(lines)


def _fmt(value: Any) -> str:
    if value is None:
        return "—"
    try:
        return f"{float(value):.3f}"
    except (TypeError, ValueError):
        return str(value)
